"""Variant B - the same seven tables as a Databricks job with one task per table.

Writes `databricks.yml` next to this file from `../pipeline/pipeline.yaml`: one
`notebook_task` per table, `depends_on` from pipetree's dependency tree, a retry
policy per task. Every task runs `../shared/run_pipeline.py` with
`select=<table>`, so the merge code is pipetree in both variants - only the
orchestration moves from the package to the job.

    uv run --with pipetree-meta python generate.py

Generated on purpose, not written by hand: the point of the post is what this
file looks like at 7, 50 and 170 tables.
"""

from __future__ import annotations

from pathlib import Path

import yaml
from pipetree.config.loader import load_config
from pipetree.graph.builder import build_graph
from pipetree.model import PipelineConfig

HERE = Path(__file__).resolve().parent
CONFIG = HERE.parent / "pipeline" / "pipeline.yaml"

RETRIES = 2  # pipetree's default is 3 attempts = 2 retries
RETRY_INTERVAL_MS = 30_000


def task_key(fqn: str) -> str:
    return fqn.replace(".", "__")


def job() -> dict:
    config = PipelineConfig.from_validated_raw(load_config(CONFIG))
    graph = build_graph(config, CONFIG.parent)
    tasks = []
    for fqn in graph.order:
        task: dict = {
            "task_key": task_key(fqn),
            "job_cluster_key": "shared",
            "max_retries": RETRIES,
            "min_retry_interval_millis": RETRY_INTERVAL_MS,
            "notebook_task": {
                "notebook_path": "../shared/run_pipeline.py",
                "base_parameters": {
                    "catalog": "${var.catalog}",
                    "config_path": "${workspace.file_path}/pipeline/pipeline.yaml",
                    "select": fqn,
                    "max_workers": "1",
                    "faults": "{{job.parameters.faults}}",
                    "init": "{{job.parameters.init}}",
                },
            },
            "libraries": [
                {"pypi": {"package": "pipetree-meta[azure]==${var.pipetree_version}"}}
            ],
        }
        parents = sorted(graph.edges[fqn])
        if parents:
            task["depends_on"] = [{"task_key": task_key(p)} for p in parents]
        tasks.append(task)

    return {
        "bundle": {"name": "pipetree-part4-b-job-tasks"},
        "include": ["../shared/variables.yml"],
        "sync": {"paths": ["../pipeline", "../shared"]},
        "resources": {
            "jobs": {
                "pipetree_b_job_tasks": {
                    "name": "part 4 / B - a job with one task per table",
                    "parameters": [
                        {"name": "faults", "default": ""},
                        {"name": "init", "default": "false"},
                    ],
                    "job_clusters": [
                        {
                            "job_cluster_key": "shared",
                            "new_cluster": "${var.single_node_cluster}",
                        }
                    ],
                    "tasks": tasks,
                }
            }
        },
        "targets": {"dev": {"default": True}},
    }


def main() -> None:
    header = (
        "# Variant B - a job with one task per table. GENERATED by generate.py from\n"
        "# ../pipeline/pipeline.yaml: do not edit, regenerate.\n"
        "#\n"
        "#   databricks bundle deploy -t dev\n"
        "#   databricks bundle run pipetree_b_job_tasks -t dev\n\n"
    )
    text = yaml.safe_dump(job(), sort_keys=False, width=100)
    (HERE / "databricks.yml").write_text(header + text)
    print(
        f"wrote {HERE / 'databricks.yml'}: {text.count(chr(10))} lines, {len(job()['resources']['jobs']['pipetree_b_job_tasks']['tasks'])} tasks"
    )


if __name__ == "__main__":
    main()
